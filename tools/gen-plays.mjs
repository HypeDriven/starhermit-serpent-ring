// Writes the native play scripts (tests/native/*.play) from bot plans made
// with the real rules and the client's round code (tools/plan.mjs): menus are
// clicked (desktop) or touched (phone), the ring is steered by holding and
// releasing the steering keys on exact frames, and each script expects the
// round's exact end (its results line: total, peak length, ticks).
// Timing (measured): the render check plays one fixed step a frame and a
// fixed step is one rules tick (30 Hz); the `until` that first sees the HUD
// matches on the frame that played tick 2, and a key line right after it acts on
// tick 3; each key line takes one frame, `frames N` takes N + 1.
//   node tools/gen-plays.mjs            (rewrites tests/native/*.play)
// tests/native.mjs imports dailyScript() to plan today's Daily at test time.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { plan } from './plan.mjs';
import { JOURNEY, LESSONS, CHALLENGES, dailyContent } from '../js/content.js';
import { meters } from '../js/session.js';
import { T, setLocale } from '../js/i18n.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
setLocale('en-US');

/** The key lines of a plan, timed from the HUD's first frame (tick 1). */
export function steerLines(p, start = 2) {
  const out = [];
  let at = start; // the tick the last line acted on: the until's frame has played tick 2 
  for (const inp of p.inputs) {
    if (!inp.line) continue;
    const gap = inp.t - at - 1;
    if (gap < 0) throw new Error(`key line for tick ${inp.t} comes too early (plan with firstTick ${start + 1})`);
    if (gap > 0) out.push(`frames ${gap - 1}`);
    out.push(inp.line);
    at = inp.t;
  }
  return out;
}
/** The results line the round ends on (main.ts / screens.ts results). */
export function totalLine(p) {
  const r = p.result;
  return T('Total {total} · peak length {len} m · ticks {ticks}', { total: r.total, len: meters(r.peakTrail), ticks: r.elapsedTicks });
}
/** A round started by the line before (`click` or `touch`): the until that first sees the HUD (text no menu has) is tick 2's frame. */
function roundScript(p, hudText) {
  return [`until 300 ${hudText}`, ...steerLines(p), `until ${p.ticks + 200} Total`, `expect ${totalLine(p)}`];
}

export function dailyScript(item) {
  const p = plan(item, {});
  return [
    `# Generated by tools/gen-plays.mjs at test time: today's Daily (${item.id}) played by the bot to its end.`,
    '# viewport 1280x800@1',
    'until 600 Steer, gather light',
    'frames 10',
    'click =Daily Challenge',
    'until 300 Play the daily challenge',
    'frames 5',
    'click =Play the daily challenge',
    ...roundScript(p, '· length'),
    'frames 5',
    'save daily-results',
    '',
  ].join('\n');
}

function write(name, lines) {
  writeFileSync(join(root, 'tests', 'native', name), lines.join('\n') + '\n');
  console.log(`wrote tests/native/${name}`);
}

